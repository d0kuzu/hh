def build_input(profile: dict, vacancy: Vacancy) -> str:
    return json.dumps({
        "candidate_facts": profile,
        "vacancy_data": {
            "title": vacancy.title, "company": vacancy.company,
            "description": vacancy.description[:24000], "contact": vacancy.contact,
            "address": vacancy.address, "salary": vacancy.salary, "schedule": vacancy.schedule,
        },
    }, ensure_ascii=False)
